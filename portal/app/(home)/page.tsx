import { readFile } from 'node:fs/promises';
import path from 'node:path';
import Link from 'next/link';
import { Reconcile } from '@/components/reconcile';
import { ButtonLink, Section, StatusChip } from '@/components/ui';
import { getSnapshot, overall } from '@/lib/snapshot';
import { repoUrl } from '@/lib/site';
import { ago } from '@/lib/time';

export const revalidate = 300;

const steps = [
  { n: '01', title: 'Request', body: 'A YAML file under requests/<team>/, written by hand or generated by the catalog.', tool: 'git' },
  { n: '02', title: 'Lint', body: 'Schema, unknown fields, ownership, naming and team budget — with line-level PR annotations.', tool: 'gantry-lint (Go)' },
  { n: '03', title: 'Policy', body: 'Admission policies are unit-tested with fixtures that must pass and fixtures that must fail.', tool: 'Kyverno' },
  { n: '04', title: 'Prove', body: 'A fresh cluster is built, every request applied, and isolation asserted at runtime.', tool: 'kind + Crossplane' },
];

const stack = [
  { name: 'Crossplane v2', role: 'Platform API: XRDs and composition pipelines' },
  { name: 'CloudNativePG', role: 'Postgres operator behind PostgresInstance' },
  { name: 'Kyverno', role: 'CEL admission policies, tested offline' },
  { name: 'Pod Security + NetworkPolicy', role: 'Tenant isolation, enforced and asserted' },
  { name: 'Go', role: 'gantry-lint request validator' },
  { name: 'GitHub Actions + kind', role: 'Ephemeral cluster for every change' },
  { name: 'Next.js + Fumadocs', role: 'This portal, catalog and docs' },
  { name: 'Mermaid', role: 'Architecture diagrams as code' },
];

const roadmap = [
  { title: 'Platform APIs', state: 'done', note: 'AppEnvironment, PostgresInstance' },
  { title: 'Policy gate', state: 'done', note: 'gantry-lint + Kyverno' },
  { title: 'Proof on every PR', state: 'done', note: 'kind e2e with isolation checks' },
  { title: 'Portal + docs', state: 'done', note: 'catalog generated from the XRDs' },
  { title: 'Live demo', state: 'done', note: 'rate-limited, runs a real reconcile' },
  { title: 'Observability + runbooks', state: 'done', note: 'alerts that link to tested runbooks' },
  { title: 'Mock cloud + own provider', state: 'next', note: 'networks, IPs, VMs via a custom Crossplane provider' },
  { title: 'Failure injection', state: 'done', note: 'nightly faults, alerts must fire' },
];

export default async function Home() {
  const [snapshot, request] = await Promise.all([
    getSnapshot(),
    readFile(path.join(process.cwd(), '..', 'requests', 'checkout', 'appenvironment.yaml'), 'utf8'),
  ]);
  const env = snapshot.resources.find((r) => r.kind === 'AppEnvironment' && r.name === 'checkout-dev');
  const state = overall(snapshot);

  return (
    <main className="flex flex-1 flex-col">
      <section className="bg-grid border-b border-line">
        <div className="mx-auto grid w-full max-w-6xl grid-cols-1 gap-12 px-4 pt-16 pb-20 sm:px-6 lg:pt-24">
          <div className="min-w-0 max-w-3xl">
            <p className="annot">Internal developer platform · portfolio project</p>
            <h1 className="mt-4 text-4xl font-semibold leading-[1.05] tracking-tight sm:text-6xl">
              Infrastructure,
              <br />
              <span className="marker">requested by pull request.</span>
            </h1>
            <p className="mt-6 max-w-2xl text-lg text-ink-2">
              gantry is a small platform you can read end to end: Crossplane APIs behind a self-service catalog, a policy
              gate in front, and a real Kubernetes cluster that proves every change — built from scratch in CI, every time.
            </p>
            <div className="mt-8 flex flex-wrap gap-3">
              <ButtonLink href="/catalog">Browse the catalog</ButtonLink>
              <ButtonLink href="/docs" variant="outline">Read the docs</ButtonLink>
              <ButtonLink href={repoUrl} variant="outline">Source on GitHub</ButtonLink>
            </div>
          </div>
          {env && <Reconcile request={request.trim()} items={env.composed} />}
        </div>
      </section>

      <Section label="How it works" title="Four gates between a request and a running resource.">
        <ol className="grid gap-px overflow-hidden rounded-lg border border-line bg-line sm:grid-cols-2 lg:grid-cols-4">
          {steps.map((s) => (
            <li key={s.n} className="flex flex-col gap-3 bg-paper p-5">
              <span className="font-mono text-xs text-ink-2">{s.n}</span>
              <h3 className="text-lg font-semibold">{s.title}</h3>
              <p className="text-sm text-ink-2">{s.body}</p>
              <span className="annot mt-auto pt-2">{s.tool}</span>
            </li>
          ))}
        </ol>
      </Section>

      <Section label="Last verified run" title="Not a mock-up: this is what the last run reported.">
        <Link href="/status" className="group block rounded-lg border border-ink bg-card p-5 transition-shadow hover:shadow-[4px_4px_0_0_var(--ink)] sm:p-6">
          <div className="flex flex-wrap items-center justify-between gap-3">
            <StatusChip ok={state.ok}>{state.ok ? 'verified' : 'attention'}</StatusChip>
            <span className="annot">{ago(snapshot.generatedAt)} · {snapshot.source === 'live' ? 'nightly run' : 'sample run'}</span>
          </div>
          <dl className="mt-6 grid grid-cols-2 gap-6 sm:grid-cols-4">
            <Stat label="Checks passed" value={`${snapshot.checks.filter((c) => c.status === 'pass').length}/${snapshot.checks.length}`} />
            <Stat label="Resources ready" value={`${snapshot.resources.filter((r) => r.ready).length}/${snapshot.resources.length}`} />
            <Stat label="Composed objects" value={String(snapshot.resources.reduce((n, r) => n + r.composed.length, 0))} />
            <Stat label="Kubernetes" value={snapshot.versions.kubernetes} />
          </dl>
          <span className="mt-6 inline-block text-sm text-ink-2 group-hover:text-ink">See every check →</span>
        </Link>
      </Section>

      <Section label="What's inside" title="Open-source parts, assembled into a platform.">
        <ul className="grid gap-3 sm:grid-cols-2 lg:grid-cols-4">
          {stack.map((s) => (
            <li key={s.name} className="rounded-lg border border-line p-4">
              <p className="font-medium">{s.name}</p>
              <p className="mt-1 text-sm text-ink-2">{s.role}</p>
            </li>
          ))}
        </ul>
      </Section>

      <Section label="Roadmap" title="Built in layers. Each one green before the next.">
        <ul className="grid gap-2 sm:grid-cols-2">
          {roadmap.map((r) => (
            <li key={r.title} data-state={r.state === 'done' ? 'ready' : 'desired'} className="resource flex items-center justify-between gap-3 rounded-md px-4 py-3">
              <span>
                <span className="block font-medium">{r.title}</span>
                <span className="block text-sm text-ink-2">{r.note}</span>
              </span>
              <StatusChip ok={r.state === 'done'}>{r.state === 'done' ? 'done' : 'next'}</StatusChip>
            </li>
          ))}
        </ul>
      </Section>
    </main>
  );
}

function Stat({ label, value }: { label: string; value: string }) {
  return (
    <div>
      <dt className="annot">{label}</dt>
      <dd className="mt-1 font-mono text-xl">{value}</dd>
    </div>
  );
}
